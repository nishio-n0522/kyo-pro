# row7が間違っている理由

# 以下は一例です。たとえば次のテストケースを考えてみます。

# ```
# N=5
# A: 3 5 5 5
# B: 3 5 5 5
# ```

# この入力は以下の通り意味します。

# - 盤面には1から5のマスがあり、ゴールはマス5です。
# - i=1のとき、A[1]=3, B[1]=3 なので、マス1からマス3へ100点、あるいは150点獲得してジャンプできます。
# - i=2のとき、A[2]=5, B[2]=5 なので、マス2からマス5へ100点、あるいは150点でジャンプ可能です。ただしマス2はそもそもマス1からは直接到達できないため「本来は到達不可能」なマスです。
# - i=3のとき、A[3]=5, B[3]=5 によりマス3からマス5へジャンプ可能（+100あるいは+150点）。
# - i=4のとき、A[4]=5, B[4]=5 によりマス4からマス5へジャンプ可能（+100あるいは+150点）。

# ここで問題になるのは、最初の不正解となったコードでは dp 配列をすべて0で初期化していることです。
# この場合、マス2は実際には到達不能にもかかわらず dp[2]=0 とみなされ、そこからマス5へのジャンプで dp[5] が (0+150)=150 と更新されてしまいます。
# 本来なら「到達不可能なマス」は非常に小さい値で初期化し、そこからの遷移が行われないようにしなければなりません。

# 一方、改善後のコードでは到達不可能な状態を -10^9 で初期化しているので、マス2は dp[2] = -10^9 のままであり、
# この状態からのジャンプでは dp[5] を更新できません。そのため、正しい最大スコアは、実際に到達可能な経路（1→3→5、あるいは1→3→4→5等）によって求まる正しい値になります。

# このようなテストケースでは、最初のコードは「到達不可能なマス2」を経由した不正な更新を行い、
# それが特定の状況下で最終的なスコアを誤った値にしてしまいます。それによってジャッジで不正解となるケースが発生します。


def main():
    N = int(input())

    A = list(map(int,input().split()))
    B = list(map(int,input().split()))

    # dp = [0] * (N+1)
 
    dp = [ -(10 ** 9) ] * (N + 1)
    dp[1] = 0

    for i in range(1, N):
        dp[A[i-1]] = max(dp[A[i-1]], dp[i]+100)
        dp[B[i-1]] = max(dp[B[i-1]], dp[i]+150)
        
    print(dp[N])

if __name__=='__main__':
    main()